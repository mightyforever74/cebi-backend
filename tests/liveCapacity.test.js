const test = require("node:test");
const assert = require("node:assert/strict");
const { parseLiveCapacityFields } = require("../routes/liveCapacityHelpers");

test("both fields omitted -> volumeM3/weightKg null, ok:true", () => {
  const result = parseLiveCapacityFields({});
  assert.deepEqual(result, { ok: true, volumeM3: null, weightKg: null });
});

test("explicit null/empty-string fields -> same as omitted", () => {
  const result = parseLiveCapacityFields({ volume_m3: "", weight_kg: null });
  assert.deepEqual(result, { ok: true, volumeM3: null, weightKg: null });
});

test("valid numeric fields (as numbers) -> parsed through", () => {
  const result = parseLiveCapacityFields({ volume_m3: 7.5, weight_kg: 500 });
  assert.deepEqual(result, { ok: true, volumeM3: 7.5, weightKg: 500 });
});

test("valid numeric fields sent as strings (mobile TextInput) -> coerced to numbers", () => {
  const result = parseLiveCapacityFields({ volume_m3: "3.2", weight_kg: "150" });
  assert.deepEqual(result, { ok: true, volumeM3: 3.2, weightKg: 150 });
});

test("zero is a valid live-capacity value (dolu arac, bos yer yok) -> not treated as missing", () => {
  const result = parseLiveCapacityFields({ volume_m3: 0, weight_kg: 0 });
  assert.deepEqual(result, { ok: true, volumeM3: 0, weightKg: 0 });
});

test("only one field reported (digerine dokunulmaz, partial report) -> diger null doner", () => {
  const result = parseLiveCapacityFields({ volume_m3: 2.1 });
  assert.deepEqual(result, { ok: true, volumeM3: 2.1, weightKg: null });
});

test("negative volume -> ok:false, invalid_volume", () => {
  const result = parseLiveCapacityFields({ volume_m3: -1 });
  assert.deepEqual(result, { ok: false, error: "invalid_volume" });
});

test("negative weight -> ok:false, invalid_weight", () => {
  const result = parseLiveCapacityFields({ weight_kg: -0.5 });
  assert.deepEqual(result, { ok: false, error: "invalid_weight" });
});

test("non-numeric volume string -> ok:false, invalid_volume", () => {
  const result = parseLiveCapacityFields({ volume_m3: "bos" });
  assert.deepEqual(result, { ok: false, error: "invalid_volume" });
});

test("non-numeric weight string -> ok:false, invalid_weight", () => {
  const result = parseLiveCapacityFields({ weight_kg: "cok" });
  assert.deepEqual(result, { ok: false, error: "invalid_weight" });
});
