/**
 * P1-3b — driver push notification language (locked, written before
 * implementation per WORKING_RULES.md "Mimari Bağlam Zorunluluğu").
 *
 * TODO_ACTIVE.md §4: "FCM/push şablonu ('Yeni Görev Atandı' backend'de) ->
 * kullanici diline gore". `public.users.language` already exists (set at
 * registration, already used by sendOTPEmail for password-reset mail) but
 * `sendPushNotification` (routes/internalBridge.js) never reads it - every
 * driver currently gets the hardcoded Turkish "Yeni Gorev Atandi" push
 * regardless of their app language. Decision (Cem, 10 Oct): full TR/EN/NL
 * push templates; any other mobile-supported language (de/fr/it/bg/es/ku)
 * or a missing/unknown value falls back to EN (never a crash, never a
 * silently blank notification).
 *
 * This locks:
 *   1. resolvePushLanguage: tr/en/nl pass through; anything else -> en.
 *   2. renderPushCopy('taskAssigned', ...): exact copy per language, and
 *      the TR copy matches the backend's EXISTING text byte-for-byte (no
 *      regression for the drivers already receiving it).
 *   3. sendPushNotification: reads the driver's `language` alongside
 *      `expo_push_token` and sends the matching copy; pre-existing
 *      no-token / no-userId no-throw behavior is unchanged.
 *
 * Do not edit this file to make it pass. Edit routes/internalBridge.js.
 * Run: node --test tests/pushLanguage.test.js
 */

const test = require("node:test");
const assert = require("node:assert/strict");
const {
  resolvePushLanguage,
  renderPushCopy,
  sendPushNotification,
} = require("../routes/internalBridge");

test("resolvePushLanguage: tr/en/nl pass through unchanged", () => {
  assert.equal(resolvePushLanguage("tr"), "tr");
  assert.equal(resolvePushLanguage("en"), "en");
  assert.equal(resolvePushLanguage("nl"), "nl");
});

test("resolvePushLanguage: any other mobile-supported language falls back to en", () => {
  for (const lang of ["de", "fr", "it", "bg", "es", "ku"]) {
    assert.equal(resolvePushLanguage(lang), "en", `expected en for ${lang}`);
  }
});

test("resolvePushLanguage: missing/unknown/garbage falls back to en, never throws", () => {
  assert.equal(resolvePushLanguage(null), "en");
  assert.equal(resolvePushLanguage(undefined), "en");
  assert.equal(resolvePushLanguage(""), "en");
  assert.equal(resolvePushLanguage("xx-not-a-real-lang"), "en");
});

const VARS = {
  taskNo: "TLP-26-00099",
  startLabel: "Waalhaven, Rotterdam",
  endLabel: "Botlek",
};

test("renderPushCopy('taskAssigned', 'tr', ...) matches the backend's existing TR text exactly (no regression)", () => {
  const copy = renderPushCopy("taskAssigned", "tr", VARS);
  assert.deepEqual(copy, {
    title: "Yeni Görev Atandı",
    body: "TLP-26-00099: Waalhaven, Rotterdam → Botlek",
  });
});

test("renderPushCopy('taskAssigned', 'en', ...) returns English copy", () => {
  const copy = renderPushCopy("taskAssigned", "en", VARS);
  assert.equal(copy.title, "New Task Assigned");
  assert.ok(copy.body.includes("TLP-26-00099"));
  assert.ok(copy.body.includes("Waalhaven, Rotterdam"));
  assert.ok(copy.body.includes("Botlek"));
});

test("renderPushCopy('taskAssigned', 'nl', ...) returns Dutch copy", () => {
  const copy = renderPushCopy("taskAssigned", "nl", VARS);
  assert.equal(copy.title, "Nieuwe taak toegewezen");
  assert.ok(copy.body.includes("TLP-26-00099"));
});

test("renderPushCopy falls back to English copy for an unsupported language (de)", () => {
  const de = renderPushCopy("taskAssigned", "de", VARS);
  const en = renderPushCopy("taskAssigned", "en", VARS);
  assert.deepEqual(de, en);
});

test("renderPushCopy falls back to English copy for a missing language", () => {
  const missing = renderPushCopy("taskAssigned", null, VARS);
  const en = renderPushCopy("taskAssigned", "en", VARS);
  assert.deepEqual(missing, en);
});

function buildFastify({ pushToken, language, fetchImpl }) {
  const calls = { fetch: [] };
  const originalFetch = global.fetch;
  global.fetch = async (url, opts) => {
    calls.fetch.push({ url, opts });
    if (fetchImpl) return fetchImpl(url, opts);
    return { ok: true, json: async () => ({}) };
  };
  const fastify = {
    pg: {
      async connect() {
        return {
          query: async () => ({ rows: [{ expo_push_token: pushToken, language }] }),
          release() {},
        };
      },
    },
    log: { info() {}, warn() {}, error() {} },
  };
  return {
    fastify,
    calls,
    restore: () => {
      global.fetch = originalFetch;
    },
  };
}

test("sendPushNotification sends the Dutch copy when the driver's language is 'nl'", async () => {
  const { fastify, calls, restore } = buildFastify({
    pushToken: "ExponentPushToken[abc]",
    language: "nl",
  });
  try {
    await sendPushNotification(fastify, {
      userId: "u1",
      templateKey: "taskAssigned",
      vars: VARS,
      data: { taskId: "t1" },
    });
    assert.equal(calls.fetch.length, 1);
    const sentBody = JSON.parse(calls.fetch[0].opts.body);
    assert.equal(sentBody.title, "Nieuwe taak toegewezen");
    assert.equal(sentBody.to, "ExponentPushToken[abc]");
  } finally {
    restore();
  }
});

test("sendPushNotification falls back to English when the driver has no language set (legacy row)", async () => {
  const { fastify, calls, restore } = buildFastify({
    pushToken: "ExponentPushToken[abc]",
    language: null,
  });
  try {
    await sendPushNotification(fastify, {
      userId: "u1",
      templateKey: "taskAssigned",
      vars: VARS,
    });
    assert.equal(calls.fetch.length, 1);
    const sentBody = JSON.parse(calls.fetch[0].opts.body);
    assert.equal(sentBody.title, "New Task Assigned");
  } finally {
    restore();
  }
});

test("sendPushNotification still skips (no fetch call) when there is no expo_push_token — no regression", async () => {
  const { fastify, calls, restore } = buildFastify({ pushToken: null, language: "tr" });
  try {
    await sendPushNotification(fastify, {
      userId: "u1",
      templateKey: "taskAssigned",
      vars: VARS,
    });
    assert.equal(calls.fetch.length, 0);
  } finally {
    restore();
  }
});

test("sendPushNotification never throws when userId is missing — no regression", async () => {
  const { restore } = buildFastify({ pushToken: "x", language: "tr" });
  try {
    await assert.doesNotReject(() =>
      sendPushNotification({}, { templateKey: "taskAssigned", vars: VARS })
    );
  } finally {
    restore();
  }
});
