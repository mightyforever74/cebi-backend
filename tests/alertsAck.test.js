const test = require("node:test");
const assert = require("node:assert/strict");
const { acknowledgeAlert } = require("../routes/alertsHelpers");

function fakeClient(rows) {
  const calls = [];
  return {
    calls,
    query: async (sql, params) => {
      calls.push({ sql, params });
      if (calls.length === 1) {
        return { rows: rows.existing };
      }
      return { rows: rows.updated };
    },
  };
}

test("acknowledgeAlert: alert does not exist (or belongs to another company) -> not_found", async () => {
  const client = fakeClient({ existing: [], updated: [] });
  const result = await acknowledgeAlert(client, {
    alertId: "a1",
    companyId: "c1",
    userId: "u1",
  });
  assert.deepEqual(result, { ok: false, reason: "not_found" });
  assert.equal(client.calls.length, 1);
});

test("acknowledgeAlert: already acknowledged -> already_acknowledged, no UPDATE sent, original values untouched", async () => {
  const existingRow = {
    id: "a1",
    acknowledged_at: "2026-10-09T10:00:00.000Z",
    acknowledged_by: "u-original",
  };
  const client = fakeClient({ existing: [existingRow], updated: [] });
  const result = await acknowledgeAlert(client, {
    alertId: "a1",
    companyId: "c1",
    userId: "u2",
  });
  assert.deepEqual(result, { ok: false, reason: "already_acknowledged" });
  assert.equal(client.calls.length, 1);
});

test("acknowledgeAlert: not yet acknowledged -> UPDATE sets acknowledged_at/by, company_id scoped", async () => {
  const existingRow = {
    id: "a1",
    acknowledged_at: null,
    acknowledged_by: null,
  };
  const updatedRow = {
    id: "a1",
    acknowledged_at: "2026-10-10T12:00:00.000Z",
    acknowledged_by: "u1",
  };
  const client = fakeClient({ existing: [existingRow], updated: [updatedRow] });
  const result = await acknowledgeAlert(client, {
    alertId: "a1",
    companyId: "c1",
    userId: "u1",
  });
  assert.deepEqual(result, { ok: true, alert: updatedRow });

  assert.equal(client.calls.length, 2);
  const [selectCall, updateCall] = client.calls;
  assert.match(selectCall.sql, /SELECT/i);
  assert.deepEqual(selectCall.params, ["a1", "c1"]);

  assert.match(updateCall.sql, /UPDATE alerts/i);
  assert.match(updateCall.sql, /acknowledged_at\s*=\s*NOW\(\)/i);
  assert.match(updateCall.sql, /acknowledged_by\s*=\s*\$/i);
  assert.match(updateCall.sql, /acknowledged_at IS NULL/i);
  assert.ok(updateCall.params.includes("u1"));
  assert.ok(updateCall.params.includes("a1"));
  assert.ok(updateCall.params.includes("c1"));
});

test("acknowledgeAlert: works independently of is_resolved (ack and resolve are separate states)", async () => {
  const existingRow = {
    id: "a1",
    acknowledged_at: null,
    acknowledged_by: null,
    is_resolved: true,
  };
  const updatedRow = {
    id: "a1",
    acknowledged_at: "2026-10-10T12:00:00.000Z",
    acknowledged_by: "u1",
    is_resolved: true,
  };
  const client = fakeClient({ existing: [existingRow], updated: [updatedRow] });
  const result = await acknowledgeAlert(client, {
    alertId: "a1",
    companyId: "c1",
    userId: "u1",
  });
  assert.equal(result.ok, true);
  assert.equal(result.alert.is_resolved, true);
});
