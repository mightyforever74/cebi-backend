/**
 * Vehicle creation quota enforcement (locked, written before
 * implementation per WORKING_RULES.md "Mimari Baglam Zorunlulugu").
 *
 * TulipFleet Connect Tier A ticari ilkesi (Cem, 2026-10-11): "Plaka/Kota
 * Korumasi - company_id altindaki yetkilendirmede tanimli lisansli arac
 * sayisi (arac kotasi) denetlenir." Su an POST /api/vehicles (server.js
 * ~L2198) hicbir kota kontrolu yapmadan INSERT ediyor - bu dosya, o
 * kontrolun is mantigini (checkVehicleQuota) kilitler, mevcut S5
 * (routes/company-plan.js TIER_LIMITS) ve "aktif arac" sayim konvansiyonu
 * (status != 'retired' - bkz. routes/superadmin.companies.js,
 * routes/superadmin.subscriptions.js) ile ayni kurallari izleyerek:
 *
 *   1. companyId yok -> {allowed:false, reason:'company_required'},
 *      hic sorgu atilmaz.
 *   2. Sirket bulunamadi -> {allowed:false, reason:'company_not_found'}.
 *   3. companies.max_vehicles DB override varsa o kullanilir; yoksa
 *      subscription_tier'in TIER_LIMITS tabanina dusulur (starter=5,
 *      professional=20, enterprise/custom=999; bilinmeyen/null tier ->
 *      starter).
 *   4. Aktif arac sayisi (status != 'retired') >= limit ise
 *      {allowed:false, reason:'quota_exceeded'} - sinirin TAM UZERINDE
 *      (== limit) de reddedilir, sadece > limit degil.
 *   5. retired araclar sayima girmez.
 *   6. DB hatasi yutulmaz, oldugu gibi yukari firlatilir.
 *
 * Do not edit this file to make it pass. Edit
 * routes/vehicleQuotaHelpers.js (yeni dosya).
 *
 * Run: node --test tests/vehicleQuota.test.js
 */

const test = require("node:test");
const assert = require("node:assert/strict");
const {
  checkVehicleQuota,
  TIER_LIMITS,
} = require("../routes/vehicleQuotaHelpers");

function fakeClient(responses) {
  const calls = [];
  return {
    calls,
    query: async (sql, params) => {
      calls.push({ sql, params });
      const next = responses[calls.length - 1];
      if (!next)
        throw new Error(
          `fakeClient: no staged response for call #${calls.length}`
        );
      return next;
    },
  };
}

test("checkVehicleQuota: missing companyId -> company_required, no query sent", async () => {
  const client = fakeClient([]);
  const result = await checkVehicleQuota(client, null);
  assert.deepEqual(result, {
    allowed: false,
    reason: "company_required",
    activeCount: null,
    maxVehicles: null,
  });
  assert.equal(client.calls.length, 0);
});

test("checkVehicleQuota: company not found -> company_not_found, stops after the company lookup", async () => {
  const client = fakeClient([{ rows: [] }]);
  const result = await checkVehicleQuota(client, "missing-company");
  assert.deepEqual(result, {
    allowed: false,
    reason: "company_not_found",
    activeCount: null,
    maxVehicles: null,
  });
  assert.equal(client.calls.length, 1);
});

test("checkVehicleQuota: active count below DB-override max_vehicles -> allowed", async () => {
  const client = fakeClient([
    { rows: [{ subscription_tier: "professional", max_vehicles: 20 }] },
    { rows: [{ active_count: 7 }] },
  ]);
  const result = await checkVehicleQuota(client, "c1");
  assert.deepEqual(result, {
    allowed: true,
    reason: null,
    activeCount: 7,
    maxVehicles: 20,
  });
});

test("checkVehicleQuota: active count exactly AT max_vehicles -> rejected (not just over)", async () => {
  const client = fakeClient([
    { rows: [{ subscription_tier: "starter", max_vehicles: 5 }] },
    { rows: [{ active_count: 5 }] },
  ]);
  const result = await checkVehicleQuota(client, "c1");
  assert.deepEqual(result, {
    allowed: false,
    reason: "quota_exceeded",
    activeCount: 5,
    maxVehicles: 5,
  });
});

test("checkVehicleQuota: active count over max_vehicles -> rejected", async () => {
  const client = fakeClient([
    { rows: [{ subscription_tier: "starter", max_vehicles: 5 }] },
    { rows: [{ active_count: 11 }] },
  ]);
  const result = await checkVehicleQuota(client, "c1");
  assert.equal(result.allowed, false);
  assert.equal(result.reason, "quota_exceeded");
});

test("checkVehicleQuota: no max_vehicles DB override -> falls back to tier base limit (starter=5)", async () => {
  const client = fakeClient([
    { rows: [{ subscription_tier: "starter", max_vehicles: null }] },
    { rows: [{ active_count: 4 }] },
  ]);
  const result = await checkVehicleQuota(client, "c1");
  assert.equal(result.maxVehicles, TIER_LIMITS.starter);
  assert.equal(result.allowed, true);
});

test("checkVehicleQuota: max_vehicles = 0 (falsy override) -> also falls back to tier base limit", async () => {
  const client = fakeClient([
    { rows: [{ subscription_tier: "professional", max_vehicles: 0 }] },
    { rows: [{ active_count: 3 }] },
  ]);
  const result = await checkVehicleQuota(client, "c1");
  assert.equal(result.maxVehicles, TIER_LIMITS.professional);
});

test("checkVehicleQuota: missing/unknown subscription_tier -> defaults to starter limit", async () => {
  const client = fakeClient([
    { rows: [{ subscription_tier: null, max_vehicles: null }] },
    { rows: [{ active_count: 0 }] },
  ]);
  const result = await checkVehicleQuota(client, "c1");
  assert.equal(result.maxVehicles, TIER_LIMITS.starter);

  const client2 = fakeClient([
    { rows: [{ subscription_tier: "some_future_tier", max_vehicles: null }] },
    { rows: [{ active_count: 0 }] },
  ]);
  const result2 = await checkVehicleQuota(client2, "c2");
  assert.equal(result2.maxVehicles, TIER_LIMITS.starter);
});

test("checkVehicleQuota: active-count query excludes retired vehicles and scopes by company_id", async () => {
  const client = fakeClient([
    { rows: [{ subscription_tier: "starter", max_vehicles: 5 }] },
    { rows: [{ active_count: 2 }] },
  ]);
  await checkVehicleQuota(client, "c1");
  const countCall = client.calls[1];
  assert.match(countCall.sql, /status\s*!=\s*'retired'/);
  assert.match(countCall.sql, /company_id\s*=\s*\$1/);
  assert.deepEqual(countCall.params, ["c1"]);
});

test("checkVehicleQuota: enterprise/custom tiers default to the 999 base limit", async () => {
  const client = fakeClient([
    { rows: [{ subscription_tier: "enterprise", max_vehicles: null }] },
    { rows: [{ active_count: 300 }] },
  ]);
  const result = await checkVehicleQuota(client, "c1");
  assert.equal(result.maxVehicles, TIER_LIMITS.enterprise);
  assert.equal(result.allowed, true);
});

test("checkVehicleQuota: a DB error from the client propagates, is not swallowed", async () => {
  const client = {
    calls: [],
    query: async () => {
      throw new Error("connection lost");
    },
  };
  await assert.rejects(
    () => checkVehicleQuota(client, "c1"),
    /connection lost/
  );
});
