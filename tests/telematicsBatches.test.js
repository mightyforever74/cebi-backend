test("runReconcileBatch: hardcoded liste yok, listActiveDeviceIds'ten gelen HER cihaz islenir (farkli sirketlerin cihazlari dahil)", async () => {
  const FILL_TIME = new Date("2026-10-01T00:00:00.000Z");
  const perDevice = {
    "DEV-ALERT": {
      vehicle_id: "veh-1",
      gps_haversine_km: 30,
      odo_actual_km: 600,
      last_fill_time: FILL_TIME,
      company_id: "company-a",
      plate_no: "34-AAA",
    },
    "DEV-CLEAN": {
      vehicle_id: "veh-2",
      gps_haversine_km: 99,
      odo_actual_km: 100,
      last_fill_time: FILL_TIME,
      company_id: "company-b",
      plate_no: "34-BBB",
    },
    "DEV-NODATA": null,
  };

  const client = fakeClient((sql, params) => {
    if (
      sql.includes("FROM public.vehicles") &&
      sql.includes("esp32_device_id IS NOT NULL")
    ) {
      return {
        rows: Object.keys(perDevice).map((id) => ({ esp32_device_id: id })),
      };
    }
    if (sql.trim() === "BEGIN;" || sql.trim() === "COMMIT;") return {};
    if (sql.includes("last_two_fuel_records")) {
      const deviceId = params[0];
      const d = perDevice[deviceId];
      if (!d) return { rows: [] };
      return {
        rows: [
          {
            vehicle_id: d.vehicle_id,
            gps_haversine_km: d.gps_haversine_km,
            odo_actual_km: d.odo_actual_km,
            last_fill_time: d.last_fill_time,
          },
        ],
      };
    }
    if (
      sql.includes("FROM public.alerts") &&
      sql.includes("gps_odometer_deviation")
    ) {
      return { rows: [] }; // mükerrer yok
    }
    if (sql.includes("SELECT company_id, plate_no FROM public.vehicles")) {
      const vehicleId = params[0];
      const d = Object.values(perDevice).find(
        (x) => x && x.vehicle_id === vehicleId
      );
      return { rows: [{ company_id: d.company_id, plate_no: d.plate_no }] };
    }
    if (sql.trim().startsWith("INSERT INTO public.alerts")) {
      // company_id farkli sirketler icin dogru geciyor mu dogrula
      assert.equal(params[4], "company-a");
      return { rows: [{ id: "alert-1" }] };
    }
    throw new Error("unexpected sql: " + sql);
  });

  const { processed, results } = await runReconcileBatch(client);

  assert.equal(processed, 3);
  assert.equal(
    results.find((r) => r.deviceId === "DEV-ALERT").status,
    "alert_created"
  );
  assert.equal(results.find((r) => r.deviceId === "DEV-CLEAN").status, "clean");
  assert.equal(
    results.find((r) => r.deviceId === "DEV-NODATA").status,
    "skipped_no_data"
  );

  // BEGIN/COMMIT cevrildi mi
  assert.ok(client.calls.some((c) => c.sql.trim() === "BEGIN;"));
  assert.ok(client.calls.some((c) => c.sql.trim() === "COMMIT;"));
});

test("runReconcileBatch: hata olursa ROLLBACK gonderilir, hata tekrar firlatilir", async () => {
  const client = fakeClient((sql) => {
    if (
      sql.includes("FROM public.vehicles") &&
      sql.includes("esp32_device_id IS NOT NULL")
    ) {
      return { rows: [{ esp32_device_id: "DEV-X" }] };
    }
    if (sql.trim() === "BEGIN;") return {};
    if (sql.trim() === "ROLLBACK;") return {};
    if (sql.includes("last_two_fuel_records")) throw new Error("db patladi");
    throw new Error("unexpected sql: " + sql);
  });

  await assert.rejects(() => runReconcileBatch(client), /db patladi/);
  assert.ok(client.calls.some((c) => c.sql.trim() === "ROLLBACK;"));
});

