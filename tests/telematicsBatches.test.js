const test = require("node:test");
const assert = require("node:assert/strict");

const {
  runFuelSnapshotBatch,
  FUEL_SNAPSHOT_QUERY,
} = require("../FEAT-007-EXT-virtual-telematics/05-integration/fuelSnapshotBatch");
const {
  runReconcileBatch,
  listActiveDeviceIds,
} = require("../FEAT-007-EXT-virtual-telematics/05-integration/reconcileBatch");
const {
  runCorrelationBatch,
  listCompanyIds,
} = require("../FEAT-007-EXT-virtual-telematics/05-integration/correlationBatch");

function fakeClient(handler) {
  const calls = [];
  return {
    calls,
    query: async (sql, params) => {
      calls.push({ sql, params });
      return handler(sql, params, calls.length);
    },
  };
}

// ── fuelSnapshotBatch ──────────────────────────────────────────────────

test("fuelSnapshotBatch: sorguda company_id filtresi/parametresi YOK (multi-tenant)", () => {
  assert.doesNotMatch(FUEL_SNAPSHOT_QUERY, /company_id/);
});

test("runFuelSnapshotBatch: birden fazla sirketin araclarini TEK sorguda isler, her biri icin dogru UPDATE gonderir", async () => {
  const client = fakeClient((sql, params) => {
    if (sql.includes("FROM public.fuel_records")) {
      // company_id parametresi YOK (0 param) — multi-tenant kaniti
      assert.equal(params, undefined);
      return {
        rows: [
          {
            id: "veh-acme",
            plate_no: "34-ACME",
            fuel_capacity: 400,
            kor_gun: 3,
            ort_tuketim: 30,
            son_odo: 1000,
            ilk_odo: 100,
            gun_araligi: 30,
          },
          {
            id: "veh-bolt",
            plate_no: "34-BOLT",
            fuel_capacity: 200,
            kor_gun: 0,
            ort_tuketim: 25,
            son_odo: 500,
            ilk_odo: 500,
            gun_araligi: 1,
          },
        ],
      };
    }
    if (sql.startsWith("UPDATE public.vehicles")) {
      return { rows: [] };
    }
    throw new Error("unexpected sql: " + sql);
  });

  const { processed, results } = await runFuelSnapshotBatch(client);

  assert.equal(processed, 2);

  // veh-acme: gunlukOrtKM=(1000-100)/30=30, korGunCapped=min(5,3)=3,
  // korMesafe=90 -> consumed=90*30/100=27 -> 400-27=373
  const updateCalls = client.calls.filter((c) =>
    c.sql.startsWith("UPDATE public.vehicles")
  );
  assert.equal(updateCalls.length, 2);
  assert.deepEqual(updateCalls[0].params, [373, "veh-acme"]);

  // veh-bolt: ayrı şirketin aracı, ayrı sonuç — iki şirket de İŞLENDİ (tek
  // sabit şirkete filtrelenmedi)
  const acmeResult = results.find((r) => r.vehicleId === "veh-acme");
  const boltResult = results.find((r) => r.vehicleId === "veh-bolt");
  assert.ok(acmeResult);
  assert.ok(boltResult);
  assert.equal(acmeResult.currentFuelLiters, 373);
});

test("runFuelSnapshotBatch: arac yoksa processed=0, UPDATE gonderilmez", async () => {
  const client = fakeClient((sql) => {
    if (sql.includes("FROM public.fuel_records")) return { rows: [] };
    throw new Error("unexpected sql: " + sql);
  });
  const { processed } = await runFuelSnapshotBatch(client);
  assert.equal(processed, 0);
});

