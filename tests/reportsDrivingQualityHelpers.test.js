const test = require("node:test");
const assert = require("node:assert/strict");

const {
  computeDrivingScore,
  computeScoreDelta,
  fetchDriverPerformanceRows,
  buildDriverPerformanceReport,
} = require("../routes/reportsDrivingQualityHelpers");

// ── computeDrivingScore (saf, mevcut formülün değişmeden extract edilmiş hali) ──

test("computeDrivingScore: >=10km, ceza uygulanir, 0'in altina dusmez", () => {
  const r = computeDrivingScore({
    total_km: 100,
    hard_brake_count: 3,
    hard_turn_count: 2,
    hard_accel_count: 1,
  });
  // penalty = (3*3 + 2*2 + 1*2) * (100/100) = 15
  assert.equal(r.driving_score, 85);
  assert.equal(r.score_note, null);
});

test("computeDrivingScore: <10km -> null skor, insufficient_distance notu", () => {
  const r = computeDrivingScore({
    total_km: 9.9,
    hard_brake_count: 0,
    hard_turn_count: 0,
    hard_accel_count: 0,
  });
  assert.equal(r.driving_score, null);
  assert.equal(r.score_note, "insufficient_distance");
});

test("computeDrivingScore: cok yuksek ceza 0'da clamp edilir", () => {
  const r = computeDrivingScore({
    total_km: 10,
    hard_brake_count: 100,
    hard_turn_count: 100,
    hard_accel_count: 100,
  });
  assert.equal(r.driving_score, 0);
});

// ── computeScoreDelta — Cem'in "yarim donem" gereksinimi ──────────────────

test("computeScoreDelta: iki donem de yeterli veri -> delta ve trend dogru", () => {
  const r = computeScoreDelta(85, 70);
  assert.equal(r.previous_driving_score, 70);
  assert.equal(r.score_delta, 15);
  assert.equal(r.trend, "up");
  assert.equal(r.trend_note, null);
});

test("computeScoreDelta: skor dustu -> trend=down, negatif delta", () => {
  const r = computeScoreDelta(60, 80);
  assert.equal(r.score_delta, -20);
  assert.equal(r.trend, "down");
});

test("computeScoreDelta: skor ayni -> trend=same, delta=0", () => {
  const r = computeScoreDelta(75, 75);
  assert.equal(r.score_delta, 0);
  assert.equal(r.trend, "same");
});

test("computeScoreDelta: onceki donem null (yeni surucu / <10km) -> YANLIS -100% YOK, insufficient_history", () => {
  const r = computeScoreDelta(85, null);
  assert.equal(r.previous_driving_score, null);
  assert.equal(r.score_delta, null);
  assert.equal(r.trend, null);
  assert.equal(r.trend_note, "insufficient_history");
});

test("computeScoreDelta: guncel donem null (bu donem <10km) -> delta hesaplanmaz, trend_note YOK (score_note zaten aciklar)", () => {
  const r = computeScoreDelta(null, 70);
  assert.equal(r.score_delta, null);
  assert.equal(r.trend, null);
  assert.equal(r.trend_note, null);
});

test("computeScoreDelta: her iki donem de null -> hicbir sey hesaplanmaz", () => {
  const r = computeScoreDelta(null, null);
  assert.equal(r.score_delta, null);
  assert.equal(r.trend, null);
  assert.equal(r.trend_note, null);
});

// ── fetchDriverPerformanceRows — DB client enjeksiyonu (fakeClient) ───────

function fakeClient(handler) {
  const calls = [];
  return {
    calls,
    query: async (sql, params) => {
      calls.push({ sql, params });
      return handler(sql, params);
    },
  };
}

test("fetchDriverPerformanceRows: from/to ikisi de parametre olarak geciyor (ust sinir NOW() DEGIL, donem sonu)", async () => {
  const client = fakeClient((sql, params) => {
    assert.match(sql, /t\.created_at >= \$2/);
    assert.match(sql, /t\.created_at < \$3/);
    assert.doesNotMatch(sql, /NOW\(\)/); // onceki donem icin NOW() yanlis ust sinir olurdu
    assert.deepEqual(params, [
      "company-1",
      "2026-01-01T00:00:00.000Z",
      "2026-02-01T00:00:00.000Z",
    ]);
    return {
      rows: [
        {
          driver_id: "d1",
          total_km: 50,
          hard_brake_count: 1,
          hard_turn_count: 0,
          hard_accel_count: 0,
        },
      ],
    };
  });

  const rows = await fetchDriverPerformanceRows(
    client,
    "company-1",
    "2026-01-01T00:00:00.000Z",
    "2026-02-01T00:00:00.000Z"
  );
  assert.equal(rows.length, 1);
  assert.equal(rows[0].driver_id, "d1");
});

// ── buildDriverPerformanceReport — orkestrasyon ────────────────────────────

test("buildDriverPerformanceReport: compareWithPrevious=false -> ikinci sorgu HIC calismaz, previous_period yok", async () => {
  let queryCount = 0;
  const client = fakeClient((sql) => {
    queryCount++;
    if (sql.includes("SELECT name FROM companies"))
      return { rows: [{ name: "Acme" }] };
    if (sql.includes("FROM drivers")) {
      return {
        rows: [
          {
            driver_id: "d1",
            first_name: "A",
            last_name: "B",
            email: "a@b.com",
            total_tasks: 5,
            completed_tasks: 5,
            delayed_tasks: 0,
            avg_duration_min: 30,
            total_km: 50,
            hard_brake_count: 0,
            hard_turn_count: 0,
            hard_accel_count: 0,
            overspeed_count: 0,
            impact_count: 0,
            total_alerts: 0,
          },
        ],
      };
    }
    throw new Error("unexpected sql: " + sql);
  });

  const report = await buildDriverPerformanceReport(client, "company-1", {
    days: 30,
    compareWithPrevious: false,
    now: new Date("2026-10-11T00:00:00.000Z"),
  });

  assert.equal(report.previous_period, undefined);
  assert.equal(report.drivers[0].previous_driving_score, undefined);
  // yalnizca company adi + tek donem sorgusu -> 2 cagri
  assert.equal(queryCount, 2);
});

test("buildDriverPerformanceReport: compareWithPrevious=true -> iki esit-uzunlukta donem, driver birlestirme ve delta dogru", async () => {
  const now = new Date("2026-10-11T00:00:00.000Z");
  const client = fakeClient((sql, params) => {
    if (sql.includes("SELECT name FROM companies"))
      return { rows: [{ name: "Acme" }] };
    if (sql.includes("FROM drivers")) {
      const [, from, to] = params;
      // guncel donem: son 30 gun; onceki donem: ondan onceki 30 gun
      if (
        from === "2026-09-11T00:00:00.000Z" &&
        to === "2026-10-11T00:00:00.000Z"
      ) {
        return {
          rows: [
            {
              driver_id: "d1",
              first_name: "A",
              last_name: "B",
              email: "a@b.com",
              total_tasks: 5,
              completed_tasks: 5,
              delayed_tasks: 0,
              avg_duration_min: 30,
              total_km: 100,
              hard_brake_count: 3,
              hard_turn_count: 0,
              hard_accel_count: 0,
              overspeed_count: 0,
              impact_count: 0,
              total_alerts: 3,
            },
            {
              driver_id: "d2",
              first_name: "C",
              last_name: "D",
              email: "c@d.com",
              total_tasks: 1,
              completed_tasks: 1,
              delayed_tasks: 0,
              avg_duration_min: 10,
              total_km: 2,
              hard_brake_count: 0,
              hard_turn_count: 0,
              hard_accel_count: 0,
              overspeed_count: 0,
              impact_count: 0,
              total_alerts: 0,
            },
          ],
        };
      }
      if (
        from === "2026-08-12T00:00:00.000Z" &&
        to === "2026-09-11T00:00:00.000Z"
      ) {
        return {
          rows: [
            {
              driver_id: "d1",
              first_name: "A",
              last_name: "B",
              email: "a@b.com",
              total_tasks: 4,
              completed_tasks: 4,
              delayed_tasks: 0,
              avg_duration_min: 30,
              total_km: 100,
              hard_brake_count: 8,
              hard_turn_count: 0,
              hard_accel_count: 0,
              overspeed_count: 0,
              impact_count: 0,
              total_alerts: 8,
            },
            // d2 onceki donemde HENUZ YOKTU (yeni surucu) -> bu donemde satiri yok
          ],
        };
      }
      throw new Error("unexpected period: " + from + " -> " + to);
    }
    throw new Error("unexpected sql: " + sql);
  });

  const report = await buildDriverPerformanceReport(client, "company-1", {
    days: 30,
    compareWithPrevious: true,
    now,
  });

  assert.deepEqual(report.previous_period, {
    days: 30,
    from: "2026-08-12T00:00:00.000Z",
    to: "2026-09-11T00:00:00.000Z",
  });

  const d1 = report.drivers.find((d) => d.driver_id === "d1");
  // d1 guncel: skor = 100 - (3*3*1) = 91; onceki: 100 - (8*3*1) = 76 -> delta +15, up
  assert.equal(d1.driving_score, 91);
  assert.equal(d1.previous_driving_score, 76);
  assert.equal(d1.score_delta, 15);
  assert.equal(d1.trend, "up");
  assert.equal(d1.trend_note, null);

  const d2 = report.drivers.find((d) => d.driver_id === "d2");
  // d2 guncel: 2km < 10km -> score null, score_note insufficient_distance
  assert.equal(d2.driving_score, null);
  assert.equal(d2.score_note, "insufficient_distance");
  // d2 onceki donemde hic satiri yok -> previous_driving_score null, YANLIS delta YOK
  assert.equal(d2.previous_driving_score, null);
  assert.equal(d2.score_delta, null);
  assert.equal(d2.trend, null);
  assert.equal(d2.trend_note, null); // guncel skor da null oldugu icin insufficient_history YAZILMAZ (score_note yeterli)
});

test("buildDriverPerformanceReport: days farkli bir deger (7) ile de calisir (sabit 30 degil)", async () => {
  const now = new Date("2026-10-11T00:00:00.000Z");
  const client = fakeClient((sql, params) => {
    if (sql.includes("SELECT name FROM companies"))
      return { rows: [{ name: "Acme" }] };
    if (sql.includes("FROM drivers")) {
      const [, from, to] = params;
      assert.ok(
        (from === "2026-10-04T00:00:00.000Z" &&
          to === "2026-10-11T00:00:00.000Z") ||
          (from === "2026-09-27T00:00:00.000Z" &&
            to === "2026-10-04T00:00:00.000Z")
      );
      return { rows: [] };
    }
    throw new Error("unexpected sql: " + sql);
  });

  const report = await buildDriverPerformanceReport(client, "company-1", {
    days: 7,
    compareWithPrevious: true,
    now,
  });
  assert.equal(report.previous_period.days, 7);
});
