/**
 * Müşteri Takip Portalı (§10, MVP-2 kalan) — şirket markalaması (logo + renk).
 *
 * Bulgu (11 Ekim 2026): MVP-2'nin diğer üç kalemi (olay zaman çizelgesi,
 * i18n, waypoint'ler) `routes/publicTrack.js` içinde zaten eksiksiz
 * kodlanmıştı (doküman güncel değildi — §9.8 playback bulgusuyla aynı
 * desen). Gerçekten eksik olan tek şey: `/v/:token` sayfası her zaman
 * sabit TulipFleet marka rengini (#5E72E4/#825EE4 gradient) ve bus
 * ikonunu kullanıyor; şirkete özel logo/renk yok, ve `companies` tablosunda
 * bunu saklayacak bir alan/okuma-yazma yolu da yoktu.
 *
 * Çözüm: ek migration gerektirmeden `companies.settings` JSONB'sinde
 * `settings.branding = {logoUrl, brandColor}` olarak saklanır (mevcut
 * settings alanı max_vehicles/max_drivers ile paylaşılır — güncelleme
 * diğer anahtarları EZMEMELİ).
 *
 * Kurallar:
 *   1. `resolveBranding(companyRow)` saf fonksiyon: settings.branding
 *      eksik/geçersizse DEFAULT_BRAND_COLOR'a ve logoUrl=null'a düşer
 *      (sayfa her zaman render edilebilir kalmalı).
 *   2. brandColor yalnız #RRGGBB formatında kabul edilir; logoUrl yalnız
 *      https:// ile başlıyorsa kabul edilir — geçersiz değer sessizce
 *      default'a düşer (publicTrack sayfası asla bozuk CSS/URL almaz).
 *   3. `updateCompanyBranding` mevcut settings'teki diğer anahtarları
 *      (örn. max_vehicles) KORUR, sadece branding alt-anahtarını günceller.
 *   4. `updateCompanyBranding` geçersiz girdide (format hatası) DB'ye
 *      UPDATE göndermeden reddeder (BrandingValidationError).
 *
 * Do not edit this file to make it pass. Edit routes/companyBrandingHelpers.js.
 *
 * Run: node --test tests/companyBrandingHelpers.test.js
 */

const test = require("node:test");
const assert = require("node:assert/strict");
const {
  DEFAULT_BRAND_COLOR,
  resolveBranding,
  getCompanyBranding,
  updateCompanyBranding,
  validateBrandingInput,
  BrandingValidationError,
} = require("../routes/companyBrandingHelpers");

function fakeClient(responses) {
  const calls = [];
  return {
    calls,
    query: async (sql, params) => {
      calls.push({ sql, params });
      const r = responses[calls.length - 1];
      if (r === undefined) throw new Error("fakeClient: beklenmeyen ek query");
      return r;
    },
  };
}

// ── resolveBranding (saf fonksiyon) ─────────────────────────────────────

test("resolveBranding: company null -> default marka, isDefault true", () => {
  const b = resolveBranding(null);
  assert.equal(b.companyName, null);
  assert.equal(b.logoUrl, null);
  assert.equal(b.brandColor, DEFAULT_BRAND_COLOR);
  assert.equal(b.isDefault, true);
});

test("resolveBranding: settings.branding yoksa default'a duser", () => {
  const b = resolveBranding({
    name: "Tulip Lojistik",
    settings: { max_vehicles: 10 },
  });
  assert.equal(b.companyName, "Tulip Lojistik");
  assert.equal(b.logoUrl, null);
  assert.equal(b.brandColor, DEFAULT_BRAND_COLOR);
  assert.equal(b.isDefault, true);
});

test("resolveBranding: gecerli branding -> aynen donuyor, isDefault false", () => {
  const b = resolveBranding({
    name: "Acme BV",
    settings: {
      branding: { logoUrl: "https://acme.nl/logo.png", brandColor: "#FF5500" },
    },
  });
  assert.equal(b.companyName, "Acme BV");
  assert.equal(b.logoUrl, "https://acme.nl/logo.png");
  assert.equal(b.brandColor, "#FF5500");
  assert.equal(b.isDefault, false);
});

test("resolveBranding: gecersiz brandColor (format disi) -> default'a duser, sayfa bozulmaz", () => {
  const b = resolveBranding({
    name: "Acme BV",
    settings: { branding: { brandColor: "javascript:alert(1)" } },
  });
  assert.equal(b.brandColor, DEFAULT_BRAND_COLOR);
});

test("resolveBranding: gecersiz logoUrl (http, data:, javascript:) -> null'a duser", () => {
  assert.equal(
    resolveBranding({
      settings: { branding: { logoUrl: "http://acme.nl/logo.png" } },
    }).logoUrl,
    null
  );
  assert.equal(
    resolveBranding({
      settings: { branding: { logoUrl: "javascript:alert(1)" } },
    }).logoUrl,
    null
  );
  assert.equal(
    resolveBranding({
      settings: { branding: { logoUrl: "data:text/html,<script>" } },
    }).logoUrl,
    null
  );
});

test("resolveBranding: settings string (JSON) olarak gelirse de parse eder", () => {
  const b = resolveBranding({
    name: "Acme BV",
    settings: JSON.stringify({ branding: { brandColor: "#112233" } }),
  });
  assert.equal(b.brandColor, "#112233");
});

test("resolveBranding: settings bozuk JSON string ise crash etmez, default'a duser", () => {
  const b = resolveBranding({ name: "Acme BV", settings: "{not json" });
  assert.equal(b.brandColor, DEFAULT_BRAND_COLOR);
  assert.equal(b.logoUrl, null);
});

// ── validateBrandingInput ────────────────────────────────────────────────

test("validateBrandingInput: gecerli hex renk ve https logo -> hata yok", () => {
  assert.deepEqual(
    validateBrandingInput({
      logoUrl: "https://acme.nl/logo.png",
      brandColor: "#5E72E4",
    }),
    []
  );
});

test("validateBrandingInput: bos/null degerler (temizleme niyeti) -> hata yok", () => {
  assert.deepEqual(
    validateBrandingInput({ logoUrl: null, brandColor: null }),
    []
  );
  assert.deepEqual(validateBrandingInput({ logoUrl: "", brandColor: "" }), []);
  assert.deepEqual(validateBrandingInput({}), []);
});

test("validateBrandingInput: gecersiz hex -> hata", () => {
  const errors = validateBrandingInput({ brandColor: "red" });
  assert.equal(errors.length, 1);
});

test("validateBrandingInput: http (https degil) logo -> hata", () => {
  const errors = validateBrandingInput({ logoUrl: "http://acme.nl/logo.png" });
  assert.equal(errors.length, 1);
});

// ── getCompanyBranding (DB okuma) ────────────────────────────────────────

test("getCompanyBranding: companies satirini okuyup resolveBranding uygular", async () => {
  const client = fakeClient([
    {
      rows: [
        { name: "Acme BV", settings: { branding: { brandColor: "#ABCDEF" } } },
      ],
    },
  ]);
  const b = await getCompanyBranding(client, "company-1");
  assert.equal(b.companyName, "Acme BV");
  assert.equal(b.brandColor, "#ABCDEF");
  assert.equal(client.calls[0].params[0], "company-1");
});

// ── updateCompanyBranding (DB yazma, merge) ──────────────────────────────

test("updateCompanyBranding: diger settings anahtarlarini (max_vehicles) KORUR", async () => {
  const client = fakeClient([
    { rows: [{ settings: { max_vehicles: 10, max_drivers: 5 } }] }, // SELECT
    {
      rows: [
        {
          name: "Acme BV",
          settings: {
            max_vehicles: 10,
            max_drivers: 5,
            branding: { brandColor: "#112233", logoUrl: null },
          },
        },
      ],
    }, // UPDATE RETURNING
  ]);

  const result = await updateCompanyBranding(client, "company-1", {
    brandColor: "#112233",
  });

  assert.equal(result.brandColor, "#112233");
  const updateCall = client.calls[1];
  const sentSettings = JSON.parse(updateCall.params[0]);
  assert.equal(sentSettings.max_vehicles, 10);
  assert.equal(sentSettings.max_drivers, 5);
  assert.equal(sentSettings.branding.brandColor, "#112233");
});

test("updateCompanyBranding: hem logoUrl hem brandColor birlikte guncellenebilir", async () => {
  const client = fakeClient([
    { rows: [{ settings: {} }] },
    {
      rows: [
        {
          name: "Acme BV",
          settings: {
            branding: {
              logoUrl: "https://acme.nl/logo.png",
              brandColor: "#112233",
            },
          },
        },
      ],
    },
  ]);

  const result = await updateCompanyBranding(client, "company-1", {
    logoUrl: "https://acme.nl/logo.png",
    brandColor: "#112233",
  });

  assert.equal(result.logoUrl, "https://acme.nl/logo.png");
  assert.equal(result.brandColor, "#112233");
});

test("updateCompanyBranding: logoUrl='' -> branding.logoUrl temizlenir (null)", async () => {
  const client = fakeClient([
    {
      rows: [
        { settings: { branding: { logoUrl: "https://acme.nl/old.png" } } },
      ],
    },
    { rows: [{ name: "Acme BV", settings: { branding: { logoUrl: null } } }] },
  ]);

  await updateCompanyBranding(client, "company-1", { logoUrl: "" });

  const sentSettings = JSON.parse(client.calls[1].params[0]);
  assert.equal(sentSettings.branding.logoUrl, null);
});

test("updateCompanyBranding: gecersiz girdi -> BrandingValidationError, DB'ye UPDATE gitmez", async () => {
  const client = fakeClient([]);

  await assert.rejects(
    () =>
      updateCompanyBranding(client, "company-1", { brandColor: "not-a-color" }),
    BrandingValidationError
  );
  assert.equal(client.calls.length, 0);
});

test("updateCompanyBranding: var olmayan sirket -> BrandingValidationError", async () => {
  const client = fakeClient([{ rows: [] }]);

  await assert.rejects(
    () =>
      updateCompanyBranding(client, "ghost-company", { brandColor: "#112233" }),
    BrandingValidationError
  );
});

test("updateCompanyBranding: company_id ilk SELECT'in ilk parametresi", async () => {
  const client = fakeClient([
    { rows: [{ settings: {} }] },
    { rows: [{ name: "X", settings: {} }] },
  ]);
  await updateCompanyBranding(client, "company-xyz", { brandColor: "#112233" });
  assert.equal(client.calls[0].params[0], "company-xyz");
  assert.equal(client.calls[1].params[1], "company-xyz");
});
