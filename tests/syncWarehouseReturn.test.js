const test = require("node:test");
const assert = require("node:assert/strict");

const {
  syncWarehouseReturn,
  ValidationError,
} = require("../services/syncWarehouseReturn");

function fakeClient(responses) {
  const calls = [];
  return {
    calls,
    query: async (sql, params) => {
      calls.push({ sql, params });
      const next = responses[calls.length - 1];
      if (!next) throw new Error(`fakeClient: no staged response for call #${calls.length}`);
      return next;
    },
  };
}

test("missing companyId/vehicleId/geofenceId -> ValidationError, no queries", async () => {
  const client = fakeClient([]);
  await assert.rejects(
    () => syncWarehouseReturn(client, null, "veh-1", "geo-1"),
    ValidationError
  );
  await assert.rejects(
    () => syncWarehouseReturn(client, "company-1", null, "geo-1"),
    ValidationError
  );
  await assert.rejects(
    () => syncWarehouseReturn(client, "company-1", "veh-1", null),
    ValidationError
  );
  assert.equal(client.calls.length, 0);
});

test("geofence is not a (active) warehouse zone -> returns null, exactly 1 query", async () => {
  const client = fakeClient([{ rows: [] }]);
  const result = await syncWarehouseReturn(client, "company-1", "veh-1", "geo-1");
  assert.equal(result, null);
  assert.equal(client.calls.length, 1);
  assert.match(client.calls[0].sql, /public\.warehouses/);
});

test("warehouse found, but no in_transit RMA tied to this vehicle -> returns null, exactly 2 queries", async () => {
  const client = fakeClient([
    { rows: [{ id: "wh-1" }] },
    { rows: [] },
  ]);
  const result = await syncWarehouseReturn(client, "company-1", "veh-1", "geo-1");
  assert.equal(result, null);
  assert.equal(client.calls.length, 2);
  assert.match(client.calls[1].sql, /enterprise\.rma_requests/);
  assert.match(client.calls[1].sql, /enterprise\.dispatch_tasks/);
  assert.match(client.calls[1].sql, /in_transit/);
});

test("match found -> UPDATE'e status/warehouse_id/appended audit_log ile gider, {id,status} doner", async () => {
  const existingAuditLog = [{ event: "pickup_scheduled", at: "2026-10-10T00:00:00.000Z" }];
  const client = fakeClient([
    { rows: [{ id: "wh-1" }] },
    { rows: [{ id: "rma-1", audit_log: existingAuditLog }] },
    { rows: [{ id: "rma-1", status: "warehouse_received" }] },
  ]);

  const result = await syncWarehouseReturn(client, "company-1", "veh-1", "geo-1");

  assert.deepEqual(result, { id: "rma-1", status: "warehouse_received" });
  assert.equal(client.calls.length, 3);

  const updateCall = client.calls[2];
  assert.match(updateCall.sql, /UPDATE enterprise\.rma_requests/);
  assert.match(updateCall.sql, /SET status = 'warehouse_received'/);
  assert.match(updateCall.sql, /WHERE id = \$\d+ AND status = 'in_transit'/);

  const [warehouseIdParam, auditLogParam, rmaIdParam] = updateCall.params;
  assert.equal(warehouseIdParam, "wh-1");
  assert.equal(rmaIdParam, "rma-1");

  const appendedLog = JSON.parse(auditLogParam);
  assert.equal(appendedLog.length, 2);
  assert.deepEqual(appendedLog[0], existingAuditLog[0]); // onceki girdi asla silinmez/degismez
  assert.equal(appendedLog[1].event, "warehouse_received");
  assert.ok(appendedLog[1].at);
});

test("rma_requests.audit_log NULL/eksik gelirse bos diziden baslar, crash etmez", async () => {
  const client = fakeClient([
    { rows: [{ id: "wh-1" }] },
    { rows: [{ id: "rma-1", audit_log: null }] },
    { rows: [{ id: "rma-1", status: "warehouse_received" }] },
  ]);

  await syncWarehouseReturn(client, "company-1", "veh-1", "geo-1");

  const appendedLog = JSON.parse(client.calls[2].params[1]);
  assert.equal(appendedLog.length, 1);
  assert.equal(appendedLog[0].event, "warehouse_received");
});

test("race condition: UPDATE 0 satir etkiler (status arada degismis) -> null doner", async () => {
  const client = fakeClient([
    { rows: [{ id: "wh-1" }] },
    { rows: [{ id: "rma-1", audit_log: [] }] },
    { rows: [] }, // RETURNING hicbir satir vermedi
  ]);

  const result = await syncWarehouseReturn(client, "company-1", "veh-1", "geo-1");
  assert.equal(result, null);
});

test("warehouse sorgusu company_id ve is_active ile scoped", async () => {
  const client = fakeClient([{ rows: [] }]);
  await syncWarehouseReturn(client, "company-1", "veh-1", "geo-1");
  const sql = client.calls[0].sql;
  const params = client.calls[0].params;
  assert.match(sql, /geofence_id = \$1/);
  assert.match(sql, /company_id = \$2/);
  assert.match(sql, /is_active = true/);
  assert.deepEqual(params, ["geo-1", "company-1"]);
});