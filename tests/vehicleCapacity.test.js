const test = require("node:test");
const assert = require("node:assert/strict");
const { parseVehicleCapacityFields } = require("../routes/vehicleCapacityHelpers");

test("all fields omitted -> volumeM3/weightKg null, hazmatClasses empty array, ok:true", () => {
  const result = parseVehicleCapacityFields({});
  assert.deepEqual(result, {
    ok: true,
    volumeM3: null,
    weightKg: null,
    hazmatClasses: [],
  });
});

test("explicit null/empty-string fields -> same as omitted", () => {
  const result = parseVehicleCapacityFields({
    cargo_capacity_volume_m3: "",
    cargo_capacity_weight_kg: null,
    hazmat_certified_classes: null,
  });
  assert.deepEqual(result, {
    ok: true,
    volumeM3: null,
    weightKg: null,
    hazmatClasses: [],
  });
});

test("valid numeric fields (as numbers) -> parsed through", () => {
  const result = parseVehicleCapacityFields({
    cargo_capacity_volume_m3: 42.5,
    cargo_capacity_weight_kg: 3200,
    hazmat_certified_classes: ["Sinif 3", "Sinif 8"],
  });
  assert.deepEqual(result, {
    ok: true,
    volumeM3: 42.5,
    weightKg: 3200,
    hazmatClasses: ["Sinif 3", "Sinif 8"],
  });
});

test("valid numeric fields sent as strings (mobile TextInput) -> coerced to numbers", () => {
  const result = parseVehicleCapacityFields({
    cargo_capacity_volume_m3: "12.5",
    cargo_capacity_weight_kg: "1000",
  });
  assert.deepEqual(result, {
    ok: true,
    volumeM3: 12.5,
    weightKg: 1000,
    hazmatClasses: [],
  });
});

test("zero is a valid capacity value, not treated as missing", () => {
  const result = parseVehicleCapacityFields({
    cargo_capacity_volume_m3: 0,
    cargo_capacity_weight_kg: 0,
  });
  assert.deepEqual(result, {
    ok: true,
    volumeM3: 0,
    weightKg: 0,
    hazmatClasses: [],
  });
});

test("negative volume -> ok:false, invalid_volume, nothing else parsed", () => {
  const result = parseVehicleCapacityFields({ cargo_capacity_volume_m3: -5 });
  assert.deepEqual(result, { ok: false, error: "invalid_volume" });
});

test("negative weight -> ok:false, invalid_weight", () => {
  const result = parseVehicleCapacityFields({ cargo_capacity_weight_kg: -1 });
  assert.deepEqual(result, { ok: false, error: "invalid_weight" });
});

test("non-numeric volume string -> ok:false, invalid_volume", () => {
  const result = parseVehicleCapacityFields({ cargo_capacity_volume_m3: "not-a-number" });
  assert.deepEqual(result, { ok: false, error: "invalid_volume" });
});

test("non-numeric weight string -> ok:false, invalid_weight", () => {
  const result = parseVehicleCapacityFields({ cargo_capacity_weight_kg: "lots" });
  assert.deepEqual(result, { ok: false, error: "invalid_weight" });
});

test("hazmat_certified_classes not an array -> ok:false, invalid_hazmat_classes", () => {
  const result = parseVehicleCapacityFields({ hazmat_certified_classes: "Sinif 3" });
  assert.deepEqual(result, { ok: false, error: "invalid_hazmat_classes" });
});

test("hazmat_certified_classes with a non-string entry -> ok:false, invalid_hazmat_classes", () => {
  const result = parseVehicleCapacityFields({ hazmat_certified_classes: ["Sinif 3", 8] });
  assert.deepEqual(result, { ok: false, error: "invalid_hazmat_classes" });
});
